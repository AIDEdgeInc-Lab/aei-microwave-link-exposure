@pytest.mark.parametrize("f", sorted(TABLE_5))
def test_coefficients_equal_table_5(f):
    kh, ah, kv, av = TABLE_5[f]
    k_h, a_h = rain_coefficients(f, "H")
    k_v, a_v = rain_coefficients(f, "V")
    assert k_h == pytest.approx(kh, rel=2e-3) and a_h == pytest.approx(ah, rel=2e-3)
    assert k_v == pytest.approx(kv, rel=2e-3) and a_v == pytest.approx(av, rel=2e-3)


def test_continuous_between_table_rows():
    # no interpolation artefacts: 7.5 GHz lies between the 7 and 8 GHz rows for both k and alpha
    k7, a7 = rain_coefficients(7.0, "V"); k8, a8 = rain_coefficients(8.0, "V"); k75, a75 = rain_coefficients(7.5, "V")
    assert k7 < k75 < k8 and min(a7, a8) - 0.2 < a75 < max(a7, a8) + 0.2


def test_ten_ghz_vertical_32_mm_h_is_near_three_quarters_of_a_db_per_km():
    # OBSERVED from Table 5 (kV = 0.01129, alphaV = 1.2156): 0.01129 * 32 ** 1.2156 = 0.763 dB/km. The 0.1.x table gave 0.071.
    assert specific_attenuation_db_km(32.0, 10.0, "V") == pytest.approx(0.763, abs=0.005)
